    private static function questionsForTopic(int $topicId, array $rows): array
    {
        $questions = [];
        $baseId = $topicId * 100;

        foreach ($rows as $i => $row) {
            [$text, $a, $b, $c, $d, $correct, $explanation] = $row;
            $questions[] = [
                'id' => $baseId + $i + 1,
                'topic_id' => $topicId,
                'question_text' => $text,
                'option_a' => $a,
                'option_b' => $b,
                'option_c' => $c,
                'option_d' => $d,
                'correct_answer' => $correct,
                'explanation' => $explanation,
            ];
        }

        return $questions;
    }
