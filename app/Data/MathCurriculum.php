namespace App\Data;

class MathCurriculum
{
    public static function topics(): array
    {
        $topics = [];
        $id = 1;

        foreach (self::curriculumByGrade() as $grade => $items) {
            foreach ($items as $item) {
                $topics[] = array_merge($item, [
                    'id' => $id,
                    'grade_level' => $grade,
                    'video_url' => $item['video_url'] ?? null,
                    'video_title' => $item['video_title'] ?? null,
                ]);
                $id++;
            }
        }

        return $topics;
    }

    public static function questions(): array
    {
        $all = [];

        foreach (self::questionBank() as $topicId => $rows) {
            $all = array_merge($all, self::questionsForTopic($topicId, $rows));
        }

        return $all;
    }

